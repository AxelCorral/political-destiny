import type { Condition, GameEventDefinition } from "@/game/types";

import { bloc, directChoice, event, hidden, stat, world } from "../authoring";

/**
 * V3 — cartes déclenchées par le directeur de campagne
 * (`src/game/engine/campaignDirector.ts`). Elles ne sont jamais tirées au hasard : le
 * directeur pose le drapeau `director:card:<id>` et place la carte en tête de file.
 */

const anyCampaignPhase = { pre_campaign: 1, campaign: 1, official_campaign: 1 } as const;

function cardFlag(id: string): Condition {
  return { kind: "flag", key: `director:card:${id}`, equals: true };
}

type DirectorEventInput = Parameters<typeof event>[0];

function directorEvent(
  input: Omit<DirectorEventInput, "phaseWeights" | "eligibility"> & {
    eligibility?: Condition[];
  },
): GameEventDefinition {
  return event({
    ...input,
    phaseWeights: anyCampaignPhase,
    baseWeight: 0.0001,
    oncePerRun: input.oncePerRun ?? true,
    eligibility: [cardFlag(input.id), ...(input.eligibility ?? [])],
  });
}

